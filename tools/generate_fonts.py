"""Generate Inter text and Geist Mono Light numerals for the retained Figma layout."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
CHARS = list(range(32, 256)) + [0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026]

def main():
    lines = ['// Generated by tools/generate_fonts.py; fonts are licensed under SIL OFL.', '#pragma once', '#include <cstdint>', 'namespace home {',
             'struct Glyph { uint32_t code, offset; uint16_t width, height, advance; int16_t left, top; };',
             '// Glyph advances and tracking use 1/64 pixel units to retain Figma letter spacing.',
             'struct Font { const uint8_t* pixels; const Glyph* glyphs; uint16_t count, height, capHeight; int16_t tracking; };']
    specs = [
        ('small', 'Inter', 14, 500, 0),
        ('label', 'Inter', 13, 500, 1.4),
        ('day', 'Inter', 13, 500, 1),
        ('body', 'Inter', 20, 500, 0),
        ('title', 'Inter', 29, 600, 0),
        ('route', 'Inter', 36, 650, 0),
        ('trainTitle', 'Inter', 29, 500, 0),
        ('trainRoute', 'Inter', 36, 400, 0),
        ('trainTime', 'Inter', 16, 600, 0),
        ('trainHero', 'GeistMono', 194, 300, -5),
        ('trainHeroCompact', 'GeistMono', 150, 300, -4),
        ('trainLater', 'GeistMono', 46, 300, -1),
        ('trainLaterCompact', 'GeistMono', 32, 300, -1),
        ('big', 'GeistMono', 110, 300, -5),
        ('compact', 'GeistMono', 88, 300, -4),
        ('narrow', 'GeistMono', 64, 300, -3),
        ('tinyNumber', 'GeistMono', 44, 300, -2),
        ('unit', 'Inter', 17, 500, 0),
        ('time', 'Inter', 16, 500, 0),
        ('departure', 'Inter', 16, 500, 0),
        ('agenda', 'Inter', 22, 500, -.4),
    ]
    for name, family, size, weight, tracking in specs:
        font = ImageFont.truetype(str(ROOT / f'assets/{family}.ttf'), size)
        font.set_variation_by_axes([14, weight] if family == 'Inter' else [weight])
        data, glyphs = [], []
        chars = CHARS if family != 'GeistMono' else [32, 45, 46] + list(range(48, 58))
        for code in chars:
            char = chr(code)
            left, top, right, bottom = font.getbbox(char, anchor='lt')
            # Every glyph is positioned relative to a common ascender baseline.
            left, top, right, bottom = font.getbbox(char, anchor='ls')
            w, h = right-left, bottom-top
            img = Image.new('L', (max(w, 1), max(h, 1)), 0)
            ImageDraw.Draw(img).text((-left, -top), char, font=font, fill=255, anchor='ls')
            bits = [1 if img.getpixel((x,y)) >= 120 else 0 for y in range(h) for x in range(w)]
            offset = len(data)
            for i in range(0, len(bits), 8):
                data.append(sum(b << (7-j) for j,b in enumerate(bits[i:i+8])))
            glyphs.append((code, offset, w, h, round(font.getlength(char)*64), left, top))
        lines.append(f'inline constexpr uint8_t {name}Pixels[] = {{'+','.join(map(str,data))+'};')
        lines.append(f'inline constexpr Glyph {name}Glyphs[] = {{'+','.join('{'+','.join(map(str,g))+'}' for g in glyphs)+'};')
        cap_height = -font.getbbox('H', anchor='ls')[1]
        lines.append(f'inline constexpr Font {name}Font = {{{name}Pixels,{name}Glyphs,{len(glyphs)},{size},{cap_height},{round(tracking*64)}}};')
    lines.append('}')
    (ROOT/'shared/fonts.h').write_text('\n'.join(lines)+'\n')

if __name__ == '__main__':
    main()
